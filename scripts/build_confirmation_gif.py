"""Regenerate the email GIF and its bundled inline attachment (requires Pillow)."""
from pathlib import Path
import base64
import math
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.test-tools' / 'image-tools'))
from PIL import Image, ImageDraw, ImageFont

width, height = 660, 290
rng = random.Random(5596)
colors = ['#111511', '#356047', '#c4a15b', '#dedfd9', '#76382d']
pieces = [(rng.randrange(width), rng.randrange(height), rng.choice(colors),
           rng.randrange(4, 9), rng.random() * math.tau, rng.choice([1, 2])) for _ in range(58)]
fonts = Path('C:/Windows/Fonts')
title = ImageFont.truetype(str(fonts / 'georgiaz.ttf'), 83)
label = ImageFont.truetype(str(fonts / 'georgia.ttf'), 13)
frames = []
for frame in range(48):
    canvas = Image.new('RGB', (width, height), '#fcfcfa')
    draw = ImageDraw.Draw(canvas)
    for x, y, color, size, angle, speed in pieces:
        y = (y + frame * height * speed / 48) % height
        # Keep the typography clear while the confetti falls around it.
        if 85 < x < width - 85 and 72 < y < 244:
            continue
        angle += frame * math.tau / 48
        points = [(x + a * math.cos(angle) - b * math.sin(angle),
                   y + a * math.sin(angle) + b * math.cos(angle))
                  for a, b in [(-size / 2, -size), (size / 2, -size),
                               (size / 2, size), (-size / 2, size)]]
        draw.polygon(points, fill=color)
    draw.text((width / 2, 83), 'Y O U R  M E E T I N G  I S  C O N F I R M E D',
              font=label, fill='#356047', anchor='mm')
    draw.text((width / 2, 157), 'Thank you!', font=title, fill='#10130f', anchor='mm')
    draw.line((280, 230, 380, 230), fill='#c4a15b', width=2)
    frames.append(canvas)

asset = ROOT / 'static' / 'brand' / 'confirmation-confetti.gif'
frames[0].save(asset, save_all=True, append_images=frames[1:], duration=80,
               loop=0, optimize=True, disposal=2)
encoded = base64.b64encode(asset.read_bytes()).decode('ascii')
(ROOT / 'supabase' / 'functions' / 'dispatch-bookings' / 'confirmation-image.js').write_text(
    '// Generated by scripts/build_confirmation_gif.py; embedded to avoid remote image requests.\n'
    f"export const confirmationGif = '{encoded}';\n", encoding='utf-8')
print(f'Generated {asset.name}: {asset.stat().st_size:,} bytes, {len(frames)} frames')
